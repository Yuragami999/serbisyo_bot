function t(string $key): string {
    global $translations;
    $lang = CURRENT_LANG;
    return $translations[$lang][$key]
        ?? $translations['en'][$key]
        ?? $key;
}

 
function t_array(string $key): array {
    global $translations;
    $lang = CURRENT_LANG;
    return $translations[$lang][$key]
        ?? $translations['en'][$key]
        ?? [];
}
